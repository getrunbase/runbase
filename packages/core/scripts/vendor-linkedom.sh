#!/bin/sh
# Regenerates src/functions/linkedom.gen.ts: linkedom (ISC, WebReflection)
# bundled by `deno bundle` into a single module without imports, exposed as a string
# to be written into the functions sandbox folder (parseHTML,
# DOMParser). Usage: scripts/vendor-linkedom.sh [version]
set -e
VERSION=${1:-0.18.12}
DIR=$(cd "$(dirname "$0")/.." && pwd)
TMP=$(mktemp -d)
printf 'export { parseHTML, DOMParser } from "npm:linkedom@%s";\n' "$VERSION" > "$TMP/entry.ts"
deno bundle --no-config --node-modules-dir=none --platform=deno --minify "$TMP/entry.ts" -o "$TMP/out.js"
node -e '
const fs = require("fs");
const [src, dest, version] = process.argv.slice(1);
// Only remaining require: `canvas` (optional, built-in fallback). node:module is
// refused by the sandbox: replaced by a require that always fails.
const shim = "import{createRequire as __deno_internal_createRequire} from \"node:module\";";
let code = fs.readFileSync(src, "utf8");
if (!code.includes(shim)) throw new Error("bundle: node:module shim not found");
code = code.replace(shim, "const __deno_internal_createRequire=()=>(m)=>{throw new Error(\"require(\"+m+\") unavailable\")};");
if (/from\s*"node:|import\(/.test(code)) throw new Error("bundle: remaining import");
fs.writeFileSync(dest,
  "// Generated by scripts/vendor-linkedom.sh (linkedom@" + version + ", ISC): do not edit.\n" +
  "export default " + JSON.stringify(code) + ";\n");
' "$TMP/out.js" "$DIR/src/functions/linkedom.gen.ts" "$VERSION"
rm -rf "$TMP"
