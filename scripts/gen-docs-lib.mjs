// MDX rendering of the docs references: pure functions, no access to the
// app code. scripts/gen-docs.mts collects the data (OpenAPI, MCP tools,
// nodes) and calls these functions. Deterministic output: stable sort, no date.
//
// Languages: every render function takes a locale `l` = { t, tr }.
// - t(key, vars): fixed prose of the templates (apps/docs/messages/<lang>/generated.json).
// - tr(id, en): a text coming from the code (English only in the code),
//   translated by a stable id (apps/docs/translations/<lang>/generated.json).
// The default locale is English.
import { readFileSync } from "node:fs";
import { join } from "node:path";

const docsDir = join(import.meta.dirname, "../apps/docs");

export function loadMessages(lang) {
  return JSON.parse(
    readFileSync(join(docsDir, `messages/${lang}/generated.json`), "utf8"),
  );
}

// Template message `key` ("a.b") with {var} placeholders.
export function format(messages, key, vars = {}) {
  const v = key.split(".").reduce((o, k) => o?.[k], messages);
  if (typeof v !== "string") throw new Error(`missing message ${key}`);
  return v.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

// Locale: `translations` = { id: { en, fr } }. A text is translated only
// when the entry exists and its `en` is the current English text (a changed
// source text makes the translation stale). Missing or stale ids are
// collected in `missing` (the English text is used meanwhile).
export function locale(lang, messages, translations = null) {
  const missing = new Map();
  return {
    lang,
    missing,
    t: (key, vars) => format(messages, key, vars),
    tr: (id, en) => {
      if (!translations || en == null || en === "") return en;
      const e = translations[id];
      if (e && e.en === en && e[lang]) return e[lang];
      missing.set(id, en);
      return en;
    },
  };
}

export const EN = locale("en", loadMessages("en"));

export const BANNER =
  "{/* Generated by scripts/gen-docs.mts (pnpm gen:docs). Do not edit by hand. */}";

// Free text -> MDX: braces and angle brackets escaped (otherwise JSX/expressions).
export function mdxText(s) {
  return String(s ?? "")
    .replace(/\\/g, "\\\\")
    .replace(/[{}]/g, (c) => `\\${c}`)
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
}

// Safe YAML attribute value (frontmatter).
const yaml = (s) => JSON.stringify(String(s));

function page(title, description, body) {
  return [
    "---",
    `title: ${yaml(title)}`,
    `description: ${yaml(description)}`,
    "---",
    "",
    BANNER,
    "",
    body.trim(),
    "",
  ].join("\n");
}

const json = (v) => "```json\n" + JSON.stringify(v, null, 2) + "\n```";

// Stable anchor of a heading (same rule as github-slugger for our names).
export const slug = (s) =>
  String(s)
    .toLowerCase()
    .replace(/[^a-z0-9 _-]/g, "")
    .replace(/ /g, "-");

// Properties of an object JSON Schema -> Markdown table.
// `id`: translation id prefix of the parameter descriptions (`<id>.<name>`).
export function paramsTable(schema, l = EN, id = "") {
  const props = schema?.properties ?? {};
  const keys = Object.keys(props);
  if (!keys.length) return l.t("noParameters");
  const required = new Set(schema.required ?? []);
  const type = (p) =>
    p.type
      ? [].concat(p.type).join(" \\| ")
      : p.enum
        ? "enum"
        : p.anyOf || p.oneOf
          ? "union"
          : p.$ref
            ? p.$ref.split("/").pop()
            : "any";
  const rows = keys.map((k) => {
    const p = props[k] ?? {};
    const desc = [
      p.in ? l.t(`api.in.${p.in}`) : "",
      l.tr(`${id}.${k}`, p.description),
      p.enum
        ? l.t("oneOf", { values: p.enum.map((e) => `\`${e}\``).join(", ") })
        : "",
    ]
      .filter(Boolean)
      .join(" ");
    return `| \`${k}\` | ${mdxText(type(p))} | ${l.t(required.has(k) ? "yes" : "no")} | ${mdxText(desc).replace(/\|/g, "\\|").replace(/\n/g, " ")} |`;
  });
  const h = (k) => l.t(`table.${k}`);
  return [
    `| ${h("name")} | ${h("type")} | ${h("required")} | ${h("description")} |`,
    "| --- | --- | --- | --- |",
    ...rows,
  ].join("\n");
}

// MCP tools: { name, description, inputSchema (JSON Schema) }.
// One page per tool group (`records.*` -> mcp/records.mdx) plus an index
// (mcp/index.mdx, same URL as the former single page) and the sidebar order
// (mcp/meta.json). Returns { "<relative path>": content }.
export function renderMcp(tools, l = EN) {
  const sorted = [...tools].sort((a, b) => a.name.localeCompare(b.name));
  const groups = new Map();
  for (const t of sorted) {
    const g = t.name.split(".")[0];
    if (!groups.has(g)) groups.set(g, []);
    groups.get(g).push(t);
  }
  const files = {};
  // Anchors of the former single page (#recordsupsert): the index sends
  // them to the group page, so old deep links keep working.
  const anchors = {};
  const index = [l.t("mcp.intro", { count: sorted.length }), `## ${l.t("mcp.groups")}`];
  const rows = [];
  for (const [g, list] of groups) {
    const body = [];
    for (const t of list) {
      anchors[slug(t.name)] = g;
      body.push(
        `## ${t.name}`,
        mdxText(l.tr(`mcp.${t.name}`, t.description) || l.t("noDescription")),
        paramsTable(t.inputSchema, l, `mcp.${t.name}`),
      );
    }
    rows.push(
      `- [${g}](/docs/reference/mcp/${g}): ${list.map((t) => `\`${t.name}\``).join(", ")}`,
    );
    files[`${g}.mdx`] = page(
      g,
      l.t("mcp.groupDescription", { group: g }),
      body.join("\n\n"),
    );
  }
  index.push(rows.join("\n"), `<McpAnchorRedirect anchors={${JSON.stringify(anchors)}} />`);
  files["index.mdx"] = page(
    l.t("mcp.title"),
    l.t("mcp.description"),
    index.join("\n\n"),
  );
  files["meta.json"] =
    JSON.stringify({ title: l.t("mcp.title"), pages: ["index", ...groups.keys()] }, null, 2) + "\n";
  return files;
}

// Workflow nodes: { type, label, description, branches, inputSchema,
// outputSchema, connector? }.
export function renderNodes(nodes, l = EN) {
  const sorted = [...nodes].sort((a, b) => a.type.localeCompare(b.type));
  const core = sorted.filter((n) => !n.connector);
  const connectors = sorted.filter((n) => n.connector);
  const one = (n) =>
    [
      `### ${n.type}`,
      `**${mdxText(l.tr(`node.${n.type}.label`, n.label))}**. ${mdxText(l.tr(`node.${n.type}`, n.description))}`,
      l.t("nodes.branches", {
        branches: n.dynamicBranches
          ? l.t("nodes.dynamicBranches")
          : n.branches.map((b) => `\`${b}\``).join(", "),
      }),
      `#### ${l.t("nodes.input")}`,
      paramsTable(n.inputSchema, l, `node.${n.type}.input`),
      `#### ${l.t("nodes.output")}`,
      json(n.outputSchema),
    ].join("\n\n");
  const body = [
    l.t("nodes.intro"),
    `## ${l.t("nodes.builtIn")}`,
    ...core.map(one),
  ];
  if (connectors.length)
    body.push(`## ${l.t("nodes.connectors")}`, ...connectors.map(one));
  return page(
    l.t("nodes.title"),
    l.t("nodes.description"),
    body.join("\n\n"),
  );
}

// Operation keys of an OpenAPI path item (the others: servers, parameters,
// summary, description…).
const METHODS = new Set([
  "get",
  "put",
  "post",
  "delete",
  "patch",
  "head",
  "options",
  "trace",
]);

// REST API: OpenAPI 3.1 spec of /api/v1. `servers` of a path item (public
// catalog routes under /api) replaces the /api/v1 base.
export function renderApi(spec, l = EN) {
  const ops = [];
  for (const [path, item] of Object.entries(spec.paths ?? {}))
    for (const [method, op] of Object.entries(item))
      if (METHODS.has(method))
        ops.push({ path, method, op, base: item.servers?.[0]?.url ?? "/api/v1" });
  ops.sort(
    (a, b) =>
      (a.op.tags?.[0] ?? "").localeCompare(b.op.tags?.[0] ?? "") ||
      a.path.localeCompare(b.path) ||
      a.method.localeCompare(b.method),
  );
  const body = [
    mdxText(l.tr("api.info", spec.info?.description ?? "")),
    l.t("api.spec"),
  ];
  let tag;
  for (const { path, method, op, base } of ops) {
    const t = op.tags?.[0];
    if ((t ?? null) !== tag) {
      body.push(`## ${mdxText(t ? l.tr(`api.tag.${t}`, t) : l.t("api.otherTag"))}`);
      tag = t ?? null;
    }
    // Translation id of the operation (operationId, stable).
    const id = `api.${op.operationId ?? `${method} ${path}`}`;
    const params = (op.parameters ?? []).filter((p) => p.in !== "header");
    body.push(
      `### ${mdxText(op.summary ? l.tr(`${id}.summary`, op.summary) : (op.operationId ?? `${method} ${path}`))}`,
      "`" + `${method.toUpperCase()} ${base}${path}` + "`",
      mdxText(l.tr(`${id}.description`, op.description ?? "")),
    );
    if (params.length)
      body.push(
        `#### ${l.t("api.parameters")}`,
        paramsTable(
          {
            properties: Object.fromEntries(
              params.map((p) => [
                p.name,
                { ...p.schema, in: p.in, description: p.description },
              ]),
            ),
            required: params.filter((p) => p.required).map((p) => p.name),
          },
          l,
          `${id}.param`,
        ),
      );
    const req = op.requestBody?.content?.["application/json"]?.schema;
    if (req) body.push(`#### ${l.t("api.requestBody")}`, json(req));
    const codes = Object.keys(op.responses ?? {}).sort();
    if (codes.length)
      body.push(
        `#### ${l.t("api.responses")}`,
        codes
          .map(
            (c) =>
              `- \`${c}\`: ${mdxText(l.tr(`${id}.response.${c}`, op.responses[c].description ?? ""))}`,
          )
          .join("\n"),
      );
  }
  if (spec.components?.schemas)
    body.push(`## ${l.t("api.schemas")}`, json(spec.components.schemas));
  return page(
    l.t("api.title"),
    l.t("api.description"),
    body.filter(Boolean).join("\n\n"),
  );
}

// Existing Markdown page (docs/*.md): the H1 title becomes the frontmatter.
export function renderMarkdownPage(md, description) {
  const m = md.match(/^# (.+)\n/);
  const title = m ? m[1].trim() : "Untitled";
  return page(title, description, m ? md.slice(m[0].length) : md);
}
