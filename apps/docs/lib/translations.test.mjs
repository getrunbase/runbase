// French translation parity (docs/i18n.md, "Documentation site").
// Blocking: a new English page must get its French page in the same pull
// request, or be listed in translations-pending.json (shown as English on
// the French site meanwhile). An entry that is translated must be removed.
import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { parity } from "./translations.mjs";

const root = join(import.meta.dirname, "../content/docs");
const pending = JSON.parse(
  readFileSync(join(import.meta.dirname, "translations-pending.json"), "utf8"),
);

test("every English page has its French page (or is pending)", () => {
  const { missing, orphans } = parity(root);
  assert.deepEqual(orphans, [], "French files without English source");
  assert.deepEqual(
    missing.filter((f) => !pending.includes(f)),
    [],
    "missing French pages: translate them (content/docs/fr/<same path>)",
  );
  assert.deepEqual(
    pending.filter((f) => !missing.includes(f)),
    [],
    "translated: remove them from lib/translations-pending.json",
  );
});

test("parity: generated pages included, orphans detected", () => {
  const dir = mkdtempSync(join(tmpdir(), "docs-i18n-"));
  mkdirSync(join(dir, "en", "ref"), { recursive: true });
  mkdirSync(join(dir, "fr"), { recursive: true });
  writeFileSync(join(dir, "en", "index.mdx"), "# Home");
  writeFileSync(join(dir, "en", "guide.mdx"), "# Guide");
  writeFileSync(join(dir, "en", "meta.json"), '{"pages":["index"]}');
  writeFileSync(join(dir, "en", "ref", "api.mdx"), "{/* Generated by scripts/gen-docs.mts */}");
  writeFileSync(join(dir, "en", "ref", "meta.json"), '{"title":"Ref"}');
  writeFileSync(join(dir, "fr", "index.mdx"), "# Accueil");
  writeFileSync(join(dir, "fr", "old.mdx"), "# Ancien");
  assert.deepEqual(parity(dir), {
    missing: ["guide.mdx", "ref/api.mdx", "ref/meta.json"],
    orphans: ["old.mdx"],
  });
});
